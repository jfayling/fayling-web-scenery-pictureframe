import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { LUNAR_TERRAINS, decodeLunarAtlas, decodeMoonTerrain } from '../js/planet-terrain.js';
import { SCENES, sceneUniforms } from '../js/scenes.js';

test('all measured crops decode intact and each scene selects the correct atlas slice', async () => {
  const atlas = await decodeLunarAtlas();
  let end = 0;
  for (const [id, terrain] of Object.entries(LUNAR_TERRAINS)) {
    const { dem, offset, spanX, spanZ } = terrain;
    assert.equal(offset, end);
    const count = dem.width * dem.height;
    const raw = Buffer.alloc(count * 2);
    let min = Infinity, max = -Infinity;
    for (let i = 0; i < count; i++) {
      const h = atlas[offset + i];
      assert(Number.isInteger(h) && h > -12000 && h < 12000);
      raw.writeInt16LE(h, i * 2);
      min = Math.min(min, h); max = Math.max(max, h);
    }
    assert.equal(createHash('sha256').update(raw).digest('hex'), dem.sha256, id);
    assert.equal(min, dem.min); assert.equal(max, dem.max);
    const frame = new Float32Array(152);
    sceneUniforms(frame, SCENES.find((s) => s.id === id), 0, { density: 1, height: 1, mist: 1 });
    assert.equal(frame[150], dem.width);
    assert.equal(frame[151], offset);
    assert(Math.abs(frame[148] * 2 - spanX) < 0.1);
    assert(Math.abs(frame[149] * 2 - spanZ) < 0.1);
    end += count;
  }
  assert.equal(end, atlas.length);
  assert(atlas.byteLength < 128 * 1024 * 1024, 'Fits the WebGPU default storage binding limit');
});

test('predictive decoding handles row boundaries and signed 16-bit overflow exactly', async () => {
  // Fixture generated by prepare-moon.py encode_heights, including both int16 limits.
  const id = 'codec-test';
  LUNAR_TERRAINS[id] = {
    dem: { width: 4, height: 3, codec: 'gradient-zigzag-planar-gzip-v1' },
    gzip: 'H4sIAAAAAAAC//vH9I+JiZmN9T8DI9N/hv8MIAAiAY5TMScYAAAA',
  };
  try {
    assert.deepEqual(Array.from(await decodeMoonTerrain(id)),
      [32767, -32768, -1, 0, -32768, 32767, 1, -1, 0, -1, -32768, 32767]);
    LUNAR_TERRAINS[id].dem.width = 5;
    await assert.rejects(decodeMoonTerrain(id), /Invalid Moon elevation asset/);
    LUNAR_TERRAINS[id].dem.codec = 'unknown';
    await assert.rejects(decodeMoonTerrain(id), /Unsupported Moon elevation encoding/);
  } finally {
    delete LUNAR_TERRAINS[id];
  }
});
